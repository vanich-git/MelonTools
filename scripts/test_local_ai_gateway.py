#!/usr/bin/env python3
"""Exercise real gateway publication with native YAML source fixtures.

Fixtures are generated by platform regression tests and contain placeholders
__LOCAL_PORT__, __LOCAL_TOKEN__, __MODEL_ID__ and __MODEL_ALIAS__. No user
configuration or credentials are read. Only temporary loopback servers run.
"""
import argparse
import contextlib
import http.server
import json
import pathlib
import socket
import subprocess
import tempfile
import threading
import time
import urllib.error
import urllib.request

CLIENT_TOKEN = "melon-e2e-client-only"
LOCAL_TOKEN = "melon-e2e-upstream-only"
MODEL_ID = "local/e2e-publication"
MODEL_ALIAS = MODEL_ID
OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def request(port, path, body=None, token=CLIENT_TOKEN):
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(
        f"http://127.0.0.1:{port}{path}", data=data,
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
    )
    with OPENER.open(req, timeout=90) as response:
        return json.load(response)


def until(check, process, timeout=30):
    deadline = time.monotonic() + timeout
    last = None
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise AssertionError(f"gateway exited with {process.returncode}")
        try:
            result = check()
            if result:
                return result
        except (OSError, ValueError) as exc:
            last = exc
        time.sleep(0.1)
    raise AssertionError(f"condition did not converge: {last}")


class Upstream(http.server.BaseHTTPRequestHandler):
    calls = []

    def log_message(self, *_):
        pass

    def do_POST(self):
        if self.headers.get("Authorization") != f"Bearer {LOCAL_TOKEN}":
            self.send_error(401)
            return
        body = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        type(self).calls.append((self.path, body))
        if self.path != "/v1/chat/completions" or body.get("model") != MODEL_ID:
            self.send_error(400)
            return
        data = json.dumps({
            "id": "e2e", "object": "chat.completion", "created": 1, "model": MODEL_ID,
            "choices": [{"index": 0, "message": {"role": "assistant", "content": "publication-ok"}, "finish_reason": "stop"}],
            "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2},
        }).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


@contextlib.contextmanager
def upstream():
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Upstream)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield server.server_port
    finally:
        server.shutdown()
        server.server_close()
        thread.join()


def config_text(root, port, provider):
    # A deliberately unavailable egress proxy proves the local provider's
    # proxy-url: direct override actually reaches loopback.
    return f'''config-version: 8
server:
  host: "127.0.0.1"
  port: {port}
access:
  api-keys: ["{CLIENT_TOKEN}"]
oauth:
  auth-dir: "{root / 'auths'}"
management:
  disable-control-panel: true
requests:
  proxy-url: "http://127.0.0.1:1"
{provider}
'''


def write_config(path, content):
    temporary = path.with_suffix(".next")
    temporary.write_text(content)
    temporary.replace(path)


def run_fixture(engine, fixture, local_port, model_id, model_alias, wait_for_watcher=True, start_published=False,
                before_publish=None, after_chat=None, mock_upstream=False):
    provider = fixture.read_text()
    # The Rust builder accepts numeric ports and prefixes raw model IDs; its
    # checked fixture therefore retains a sentinel port and local/ prefix.
    provider = provider.replace('127.0.0.1:59999/', '127.0.0.1:__LOCAL_PORT__/')
    provider = provider.replace('local/__MODEL_ID__', model_id)
    assert '__LOCAL_PORT__' in provider, 'fixture has no local port placeholder or sentinel'
    assert '__LOCAL_TOKEN__' in provider, 'fixture has no local token placeholder'
    assert model_id in provider or '__MODEL_ID__' in provider, 'fixture has no model ID placeholder'
    for key, value in {
        "__LOCAL_PORT__": str(local_port), "__LOCAL_TOKEN__": LOCAL_TOKEN,
        "__MODEL_ID__": model_id, "__MODEL_ALIAS__": model_alias,
    }.items():
        provider = provider.replace(key, value)
    assert "melon-local-ai" in provider, "fixture has no local provider"
    with tempfile.TemporaryDirectory(prefix="melon-gateway-e2e-") as directory:
        root = pathlib.Path(directory)
        (root / "auths").mkdir()
        port = free_port()
        config = root / "config.yaml"
        write_config(config, config_text(root, port, provider if start_published else ""))
        with (root / "gateway.log").open("w+") as log:
            process = subprocess.Popen([str(engine), "-config", str(config), "--local-model"], cwd=root, stdout=log, stderr=log)
            try:
                def models():
                    return {m["id"] for m in request(port, "/v1/models").get("data", [])}
                until(lambda: request(port, "/v1/models"), process)
                if start_published:
                    until(lambda: model_alias in models(), process)
                else:
                    assert model_alias not in models(), "stopped model is advertised"
                try:
                    request(port, "/v1/models", token="incorrect")
                    raise AssertionError("gateway accepted incorrect client token")
                except urllib.error.HTTPError as exc:
                    assert exc.code == 401
                # Startup can expose HTTP before the watcher is attached. Wait
                # for its explicit readiness log, not an arbitrary sleep.
                def watcher_ready():
                    log.flush()
                    with (root / "gateway.log").open() as reader:
                        return "file watcher started for config and auth directory changes" in reader.read().lower()
                if wait_for_watcher:
                    until(watcher_ready, process)
                for cycle in range(2):
                    if before_publish is not None:
                        before_publish()
                    write_config(config, config_text(root, port, provider))
                    until(lambda: model_alias in models(), process)
                    upstream_calls_before = len(Upstream.calls)
                    result = request(port, "/v1/chat/completions", {
                        "model": model_alias, "messages": [{"role": "user", "content": "Say OK"}],
                        "max_tokens": 32, "stream": False,
                    })
                    content = result["choices"][0]["message"]["content"]
                    assert content, "chat returned empty content"
                    assert result.get('model') == model_alias, f"wrong response model: {result.get('model')}"
                    if mock_upstream:
                        assert content == 'publication-ok', 'mock upstream response was not forwarded'
                        calls = Upstream.calls[upstream_calls_before:]
                        assert calls, 'this cycle never reached the local upstream'
                        assert all(path == '/v1/chat/completions' and body.get('model') == model_id
                                   for path, body in calls), f'wrong upstream calls: {calls}'
                    if after_chat is not None:
                        after_chat()
                    write_config(config, config_text(root, port, ""))
                    until(lambda: model_alias not in models(), process)
                    try:
                        request(port, "/v1/chat/completions", {
                            "model": model_alias, "messages": [{"role": "user", "content": "must not route"}],
                            "max_tokens": 1, "stream": False,
                        })
                        raise AssertionError("removed model is still routable")
                    except urllib.error.HTTPError as exc:
                        assert exc.code in (400, 404), f"removed route still resolves: HTTP {exc.code}"
                        error_body = exc.read().decode()
                        assert model_alias in error_body, f"removed-model error lacks alias: {error_body}"
                    print(f"PASS {fixture.name}: cycle {cycle + 1}, /v1/models add/remove + authenticated chat + proxy bypass + removed route rejected")
            except Exception:
                log.flush()
                log.seek(0)
                # Isolated test credentials only; redact even these by default.
                lines = log.read().splitlines()
                important = [line for line in lines if '/v1/models' not in line]
                print('\n'.join(important)[-12000:].replace(CLIENT_TOKEN, "[client]").replace(LOCAL_TOKEN, "[upstream]"))
                raise
            finally:
                process.terminate()
                try:
                    process.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", type=pathlib.Path, required=True)
    parser.add_argument("--fixture", type=pathlib.Path, action="append", required=True)
    parser.add_argument("--runtime-port", type=int, help="Use an already isolated real runtime instead of the mock")
    parser.add_argument("--model-id", default=MODEL_ID)
    parser.add_argument("--model-alias", default=MODEL_ALIAS)
    parser.add_argument("--startup-race", action="store_true", help="Publish as soon as HTTP is ready, without waiting for watcher readiness")
    parser.add_argument("--start-published", action="store_true", help="Also verify the gateway starts with an existing local source")
    args = parser.parse_args()
    if args.runtime_port:
        for fixture in args.fixture:
            run_fixture(args.engine.resolve(), fixture, args.runtime_port, args.model_id, args.model_alias, not args.startup_race, args.start_published)
    else:
        with upstream() as port:
            for fixture in args.fixture:
                run_fixture(args.engine.resolve(), fixture, port, MODEL_ID, MODEL_ALIAS, not args.startup_race,
                            args.start_published, mock_upstream=True)
        assert Upstream.calls, "gateway never reached local upstream"
    print("PASS real gateway publication gate")


if __name__ == "__main__":
    main()
